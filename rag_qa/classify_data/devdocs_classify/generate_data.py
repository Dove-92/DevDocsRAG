def norm(q: str) -> str:
    return re.sub(r"[\s\W]+", "", q.lower())


def build(samples):
    """规范化去重，返回去重后的列表"""
    seen = set()
    out = []
    for q, l in samples:
        k = norm(q)
        if k in seen:
            continue
        seen.add(k)
        out.append((q, l))
    return out


def main():
    random.seed(42)
    prof = build(PROF)
    gen = build(GENERAL)

    def split3(lst, tr=0.7, va=0.15):
        random.shuffle(lst)
        n = len(lst)
        i = int(n * tr)
        j = int(n * (tr + va))
        return lst[:i], lst[i:j], lst[j:]

    p_tr, p_va, p_te = split3(prof)
    g_tr, g_va, g_te = split3(gen)

    train = p_tr + g_tr
    val = p_va + g_va
    test = p_te + g_te
    random.shuffle(train)
    random.shuffle(val)
    random.shuffle(test)

    outdir = os.path.join(os.path.dirname(os.path.abspath(__file__)))
    for name, data in [("train", train), ("val", val), ("test", test)]:
        path = os.path.join(outdir, f"{name}.jsonl")
        with open(path, "w", encoding="utf-8") as f:
            for q, l in data:
                f.write(json.dumps({"query": q, "label": l}, ensure_ascii=False) + "\n")
        p = sum(1 for _, l in data if l == "专业咨询")
        g = len(data) - p
        print(f"{name}.jsonl: total={len(data)} 专业咨询={p} 通用知识={g}")

    total_dedup = len(prof) + len(gen)
    total_raw = len(PROF) + len(GENERAL)
    print(f"\n去重前={total_raw} 去重后={total_dedup} 删除重复={total_raw - total_dedup}")
    print("标签集合:", sorted({l for _, l in prof + gen}))
    print("输出目录:", outdir)


if __name__ == "__main__":
    main()
